#!/usr/bin/env node
// scripts/tuning/gen-compose-table.mjs (v16.8.3 "Track Tuning": the composing guide's data, decision T9)
//
//   node scripts/tuning/gen-compose-table.mjs <guide.json> [<guide-loshu.json>]
//
// Writes utils/tuning/composeTable.ts from the v1683 survey's prototype output (never computed in the app, and never
// run in the repo: the prototype runs in the survey's own folder):
//   - guide.json (prototype G, guide.ts): for each of the 27 crystals, the keys robust at a plain DAW 440 ("standard")
//     and every robust (key, DAW tuning) option within ±45 cents, best first;
//   - guide-loshu.json (amendment A1, prototype G-A1, guide-loshu.ts: the same rule for the six Lo Shu Perfect GUT
//     tones), optional.
// The table keeps, per crystal (and per Lo Shu tone), the keys at 440 and the best PER_CRYSTAL options: the key, the
// cents from 440 and the DAW's A4 in Hz (440 · 2^(c/1200), to 0.1). Its header records both inputs' sha256.
// v16.8.3 fix round 1 (N4): an option for a key already robust at a plain 440 that is the same answer said again is left
// out before the best are taken; such a crystal can then have only its keys at 440. Fix round 2 (N1): "the same answer"
// is an option whose robust window (its `lo`..`hi` cents, every tuning in it robust) reaches 440 (lo <= 0 <= hi), not
// one within ±5 cents of 440: a wide window can hold 440 from 15 cents away (4920's G♯ +15, window −2..+23), and every
// option the ±5-cent rule left out has a window reaching 440 too.
// utils/tuning/tuning.check.ts pins the table's shape and its sha256; regenerate it (and re-pin) if musicFit, the tones
// or CHROMA_VERSION change.

import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const [guidePath, loShuPath] = process.argv.slice(2);
if (!guidePath) {
  console.error('usage: node scripts/tuning/gen-compose-table.mjs <guide.json> [<guide-loshu.json>]');
  process.exit(2);
}
const PER_CRYSTAL = 3;
const LIMIT = 45;
const OUT = fileURLToPath(new URL('../../utils/tuning/composeTable.ts', import.meta.url));
const sha = (b) => createHash('sha256').update(b).digest('hex');
const guideRaw = readFileSync(guidePath);
const guide = JSON.parse(guideRaw);
const loShuRaw = loShuPath ? readFileSync(loShuPath) : null;
const loShu = loShuRaw ? JSON.parse(loShuRaw) : {};
const KEY = /^[A-G]#?m?$/;
const hzOf = (c) => Math.round(440 * Math.pow(2, c / 1200) * 10) / 10;

function set(g, what) {
  if (!g || !Array.isArray(g.standard) || !Array.isArray(g.options)) throw new Error(`${what}: not a guide entry`);
  for (const k of g.standard) if (!KEY.test(k)) throw new Error(`${what}: a key at 440 "${k}"`);
  for (const o of g.options) if (!Number.isInteger(o.lo) || !Number.isInteger(o.hi) || !(o.lo <= o.cents && o.cents <= o.hi)) throw new Error(`${what}: an option's robust window ${JSON.stringify(o)}`);
  // (Fix round 2, N1: a key already at 440 whose window reaches 440 is the same answer.)
  const sameAnswer = (o) => g.standard.includes(o.key) && o.lo <= 0 && o.hi >= 0;
  const options = g.options.filter((o) => !sameAnswer(o)).slice(0, PER_CRYSTAL).map((o) => {
    if (!KEY.test(o.key) || !Number.isInteger(o.cents) || Math.abs(o.cents) > LIMIT) throw new Error(`${what}: an option ${JSON.stringify(o)}`);
    return { key: o.key, cents: o.cents, hz: hzOf(o.cents) };
  });
  return { at440: [...g.standard], options };
}

const crystals = Object.keys(guide).map(Number);
if (crystals.length !== 27) throw new Error(`guide.json has ${crystals.length} crystals, not 27`);
const rows = crystals.map((c) => {
  const s = set(guide[c], String(c));
  const lo = loShu[c] ? { hz: loShu[c].loShuHz, ...set(loShu[c], `Lo Shu ${c}`) } : null;
  return { crystal: c, ...s, loShu: lo };
});
for (const c of Object.keys(loShu)) if (!crystals.includes(Number(c))) throw new Error(`guide-loshu.json: ${c} is not a crystal`);

const lit = (v) => JSON.stringify(v).replace(/"([a-zA-Z0-9]+)":/g, '$1: ').replace(/,(?=[a-zA-Z{["0-9-])/g, ', ').replace(/"/g, "'");
const lines = [
  '// utils/tuning/composeTable.ts (v16.8.3 "Track Tuning": the composing guide\'s data, decision T9). GENERATED by',
  '// scripts/tuning/gen-compose-table.mjs: do not edit by hand.',
  '//',
  '// A design choice built on a measurement. Synthetic music only: the v1682 prototype pool\'s A4 = 440 renders (24 keys ×',
  '// 7 textures with bass, read by the app\'s own analyser), each played as Aetheria plays it at Standard (× 0.981818). An',
  '// option is a key and a DAW tuning (A4 = 440 · 2^(cents/1200) in the DAW); it is robust when the crystal\'s tone fits',
  '// (Key fit\'s rel <= 0.35: no duck) in at least 6 of the 7 styles at that tuning and at every cent within ±5 of it, and',
  `// it is searched within ±${LIMIT} cents (inside the analyser's ±48-cent fold). Per crystal: the keys robust at a plain 440, and`,
  `// the best ${PER_CRYSTAL} options (the widest robust window first, then the smallest shift; a key already at 440 not again where`,
  '// its robust window reaches 440: the same answer). Amendment A1: for the six crystals Lo Shu',
  '// Perfect GUT swaps, the same for the Lo Shu tone it plays (loShu; fewer than two where that is all there is).',
  `// Inputs: guide.json sha256 ${sha(guideRaw)}${loShuRaw ? `; guide-loshu.json sha256 ${sha(loShuRaw)}` : ''}.`,
  '// utils/tuning/tuning.check.ts pins its shape and its sha256. Regenerate it if musicFit, the tones or CHROMA_VERSION change.',
  '',
  'export interface ComposeOption {',
  '  /** The key, as Analyse tracks names it (\'C\'..\'B\', \'Cm\'..\'Bm\', sharps). */',
  '  readonly key: string;',
  '  /** The DAW tuning, whole cents from 440. */',
  '  readonly cents: number;',
  '  /** The DAW\'s A4: 440 · 2^(cents/1200), to 0.1 Hz. */',
  '  readonly hz: number;',
  '}',
  'export interface ComposeSet {',
  '  /** The keys robust at a plain DAW 440. */',
  '  readonly at440: readonly string[];',
  '  readonly options: readonly ComposeOption[];',
  '}',
  'export interface ComposeEntry extends ComposeSet {',
  '  readonly crystal: number;',
  '  /** A1: the Lo Shu Perfect GUT tone\'s own (its Hz), on the six crystals it swaps; else null. */',
  '  readonly loShu: (ComposeSet & { readonly hz: number }) | null;',
  '}',
  `export const COMPOSE_LIMIT_CENTS = ${LIMIT};`,
  `export const COMPOSE_PER_CRYSTAL = ${PER_CRYSTAL};`,
  'export const COMPOSE_TABLE: readonly ComposeEntry[] = [',
  ...rows.map((r) => `  ${lit(r)},`),
  '];',
  '',
];
writeFileSync(OUT, lines.join('\n'));
console.log(`composeTable.ts: ${rows.length} crystals (${rows.filter((r) => r.loShu).length} with Lo Shu options), sha256 of the table ${sha(JSON.stringify(rows))}`);
